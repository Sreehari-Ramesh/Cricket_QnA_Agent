async def odi_qna_agent(user_query):
        """This QnA agent is specifically designed to answer questions related to ODI cricket matches using a SQL database and a vector store for entity resolution, so if the query is related to ODI use this tool only. This agent will first identify relevant tables, extract entities from the user query, resolve them using fuzzy matching and embeddings, and then construct and execute SQL queries to retrieve the necessary information. Finally, it will generate a human-friendly answer based on the retrieved data. The response generated by this agent should not be altered further. """

        class GraphState(TypedDict):
                """
                Represents the state of our graph.
                Attributes:
                        question: question
                        generation: llm response
                        intermediate_results: intermediate results from sql agent
                        chat_history: previous user interractions
                        tables: complete info of the tables in db
                        columns: details of columns in each table
                        foreign_key_map: map of foreign keys in the db
                        entity_retrieval: entities retrieved from the user query
                        resolved_entities: resolved entities from the entity retrieval step

                """
                question: str
                generation: str
                intermediate_results: dict[str, list[dict]]  
                chat_history: list[str]
                tables: list[str]             
                columns: dict[str, list[str]] 
                foreign_key_map: dict[str, list[tuple[str, str, str]]]
                entity_retrieval: dict[str, list[dict]]
                resolved_entities: dict[str, list[str]]
                entities_resolved: bool

        def connect_db_sqlite(db_name):
                """Establishes a connection to the SQLite database."""
                conn = sqlite3.connect(db_name)
                return conn
        
        def load_all_tables(state):
                """
                Fetch all tables, columns, and foreign key relationships in the database.

                Returns:
                        tables (list): List of table names
                        tables_columns (list): List of {"table": <table_name>, "columns": [col1, col2, ...]}
                        foreign_keys (list): List of {"table": <table_name>, "foreign_keys": [{"from_col": ..., "to_table": ..., "to_col": ...}, ...]}
                """
                tables_columns = []
                foreign_keys = []
                pk_map = {}
                conn = connect_db_sqlite(DB_PATH)

                cursor = conn.execute(
                        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%';"
                )
                tables = [row[0] for row in cursor.fetchall()]

                for table in tables:

                        cursor = conn.execute(f"PRAGMA table_info({table});")
                        cols_info = cursor.fetchall()  
                        cols = [col[1] for col in cols_info]
                        tables_columns.append({"table": table, "columns": cols})

                        pk_map[table] = [col[1] for col in cols_info if col[5] == 1]

                        cursor = conn.execute(f"PRAGMA foreign_key_list({table});")
                        fks = [
                        {"from_col": fk[3], "to_table": fk[2], "to_col": fk[4]}
                        for fk in cursor.fetchall()
                        ]
                        foreign_keys.append({"table": table, "foreign_keys": fks})
                conn.close()

                for table_entry in tables_columns:
                        table = table_entry["table"]
                        cols = table_entry["columns"]

                        inferred_fks = []
                        for col in cols:
                                if col.endswith("_id"):
                                        for target_table, target_pks in pk_map.items():
                                                if len(target_pks) == 1 and target_pks[0] == col:
                                                        inferred_fks.append(
                                                        {"from_col": col, "to_table": target_table, "to_col": target_pks[0]}
                                                        )

                        if inferred_fks:
                                for fk_entry in foreign_keys:
                                        if fk_entry["table"] == table:
                                                fk_entry["foreign_keys"].extend(inferred_fks)

                return {"tables":tables,"columns": json.dumps(tables_columns, indent=2).replace("{", "{{").replace("}", "}}"),"foreign_key_map": json.dumps(foreign_keys, indent=2).replace("{", "{{").replace("}", "}}")}


        async def table_mapping(state):
                """use this node to get which table and related columns have to be used to answer the user query."""

                tables = state["tables"]
                columns= state["columns"]
                question = state["question"]

                template = """
                You are a precise query analysis assistant specialized in cricket-related SQL databases.
                Your task is to thoroughly analyze the user's question and determine which database tables are required to answer it.

                Instructions:

                1. You are provided with:

                List of all table names in the database.
                Schema of each table, including column names and descriptions.
                2. Analyze the user query carefully:

                Identify which tables are directly relevant to answering the query.
                A table is relevant if its data is necessary or useful for constructing a correct SQL query for the question.
                Do NOT include any unrelated tables.
                3. Edge Cases:

                If no tables are relevant, set `"relevant_tables": "No"` and return an empty list.
                If one or more tables are relevant, set `"relevant_tables": "Yes"` and list only the tables needed.
                4. Strict Output Format:

                Below given is a sample JSON structure return similar kind with proper curly brackets donot use square brackets as in the sample given below:

                [
                "relevant_tables": "Yes" or "No",
                "tables": ["table_name_1", "table_name_2"]
                ]

                Do not include extra text, explanations, or formatting.

                User Question:
                '{question}'

                Available Tables:
                '{tables}'

                Available columns/ schema: 
                '{columns}'

                Output Requirement:

                A single JSON object strictly following the format above.

                """

                prompt = PromptTemplate(input_variables=["question","tables","columns"],template=template)


                query_check_chain = (prompt | llm | JsonOutputParser())

                result = await query_check_chain.ainvoke({"question":question,"tables":tables,"columns":columns})

                try:
                        relevant_tables = result["relevant_tables"]
                        if relevant_tables == "Yes":
                                tables = result["tables"]
                                return {"question":question,"relevant_tables":tables}
                        else:
                                return{"intermediate_results":"no relevant table for the given user query"}
                except:
                        raise

        async def entity_retrieval(state):
                """Retrieve relevant entities from the database based on the user's question and the identified tables."""

                question = state["question"]

                template = """
                You are an information extractor for cricket queries. 
                Extract all cricket-related entities from the user query given below and return them as a JSON object.

                Entity types:
                - players (list of player names mentioned, can be short or full)
                - teams (list of teams mentioned)
                - tournaments (list of tournament names mentioned)
                - venues (list of stadiums/venues/cities mentioned)

                Rules:
                - Always return valid JSON.
                - If no entity of a type is found, return an empty array for that type.
                - Do not normalize names — capture them exactly as written in the user query.
                - Return only the JSON object, do not include any text, explanation, or formatting.

                Below is a sample JSON structure but in square brackets but in final response you have to use curly braces for object, square brackets for lists:

                [
                        "players": ["Player1", "Player2"],
                        "teams": ["Team1", "Team2"],
                        "tournaments": ["Tournament1", "Tournament2"],
                        "venues": ["Venue1", "Venue2"]
                ]

                Example:
                User query: "Show me Kohli's runs in World Cup 2024 final against Australia at Ahmedabad."
                Sample Output:
                [
                        "players": ["Kohli"],
                        "teams": ["Australia"],
                        "tournaments": ["World Cup 2024"],
                        "venues": ["Ahmedabad"]
                ]

                User query: "{question}"

                """

                prompt = PromptTemplate(input_variables=["question"],template=template)


                entity_chain = (prompt | llm | JsonOutputParser())

                result = await entity_chain.ainvoke({"question":question})
                print("Extracted Entities:", result)

                return {"entity_retrieval": result}

        def fuzzy_entity_resolver(state):
                """
                Resolves entities from entity_retrieval by performing fuzzy search in the database.
                """
                entities = state["entity_retrieval"]
                
                table_col_map = {
                        "player": [("player_bio", "player_full_name")],
                        "team": [("matches", "team1"), ("matches", "team2")],
                        "tournament": [("tournaments", "tournament_name")],
                        "venue": [("matches", "venue")],
                }

                resolved_entities = {}
                any_resolved = False
                conn = sqlite3.connect(DB_PATH)
                cur = conn.cursor()

                for entity_type, values in entities.items():
                        resolved_entities[entity_type] = []
                        sources = table_col_map.get(entity_type, [])

                        for val in values:
                                matches = []
                                for table, column in sources:
                                        cur.execute(f"""
                                        SELECT DISTINCT {column}
                                        FROM {table}
                                        WHERE {column} LIKE ?
                                        LIMIT 3
                                        """, (f"%{val}%",))
                                        matches.extend([r[0] for r in cur.fetchall()])
                        
                                if matches:
                                        any_resolved = True
                                        resolved_entities[entity_type].extend(list(set(matches)))
                                else:
                                        resolved_entities["resolved_entities"] = "False"
                                        resolved_entities[entity_type].append(val)

                        resolved_entities[entity_type] = list(set(resolved_entities[entity_type]))

                conn.close()
                return {"resolved_entities": resolved_entities,"entities_resolved": any_resolved}


        def embedding_entity_resolver(state):
                """Retrieve relevant documents from the vector store based on the resolved entities."""
                entities = state["entity_retrieval"]

                def load_vector_store():
                        embedding = HuggingFaceEmbeddings(model_name="sentence-transformers/all-MiniLM-L6-v2")
                        return FAISS.load_local("odi_vector_store/faiss_index", embedding,allow_dangerous_deserialization=True)
                vectorstore = load_vector_store()
                
                docs_found = False
                retrieved_docs = {}
                for entity_type, values in entities.items():
                        retrieved_docs[entity_type] = []
                        for value in values:
                                if value:
                                        # Use the vector store to find relevant documents
                                        docs = vectorstore.similarity_search(value, k=3)
                                        page_contents = [doc.page_content for doc in docs]
                                        if page_contents:
                                                docs_found = True
                                        retrieved_docs[entity_type].extend(page_contents)
                print("Retrieved Documents:", retrieved_docs)
                return {"resolved_entities": retrieved_docs, "entities_resolved": docs_found}


        async def sql_agent_for_relevant_tables(state):
                """Iterates over relevant tables, runs create_sql_agent, and stores intermediate results."""

                # DB_NAME = "cricketdb.db"
                engine = create_engine(f"sqlite:///{DB_PATH}")

                question = state["question"]

                if "intermediate_results" not in state or state["intermediate_results"] is None:
                        state["intermediate_results"] = {}

                db = SQLDatabase(engine=engine)
                columns_list = state["columns"]
                tables = state["tables"]
                resolve_entities = state["resolved_entities"]
                players = resolve_entities.get("players", [])
                teams = resolve_entities.get("teams", [])
                tournaments = resolve_entities.get("tournaments", [])
                venues = resolve_entities.get("venues", [])

                system = f"""
                        You are an **expert cricket database agent** designed to interact with a SQL database containing detailed cricket match, player, team, venue, and statistics data.
                        The database schema includes the following tables: **{tables}**

                        ---

                        ### 🎯 Goal

                        For every user question, you must:

                        1. **Interpret** the query using the provided resolved entities (players, teams, tournaments, venues).
                        2. **Construct** a syntactically correct SQL query that answers the question.
                        3. **Execute** the query using the provided tools.
                        4. **Analyze** the retrieved results and return a **clear, accurate, and structured answer** in plain language.

                        ---

                        ### 🛠 Core Rules

                        #### 1. Domain Awareness

                        * The database **only contains cricket-related data**.
                        * If the question is unrelated to cricket, respond exactly with:

                        ```
                        I don't know
                        ```

                        #### 2. Resolved Entities (Mandatory Usage)

                        * Always **use the resolved entities** as filters when constructing queries.
                        * Entities may include **multiple variants** (e.g., `"Virat Kohli", "V Kohli"`). Always filter with `IN (...)`, never as a concatenated string.
                        * Example:

                        ```sql
                        WHERE player_name IN ('Virat Kohli', 'V Kohli')
                        ```
                        * Resolved entities:

                        ```yaml
                        players: {players}   # full and short names
                        teams: {teams}
                        tournaments: {tournaments}
                        venues: {venues}
                        ```

                        #### 3. ID-Based Schema Design

                        * Always join IDs to get readable names:

                        * `player_id` → `player_bio` (`player_full_name`, `player_shortform`)
                        * `team_id` → team tables
                        * `match_id` → `matches` table (date, venue, teams)

                        #### 4. Query Construction

                        * Never use `SELECT *`. Select only relevant columns.
                        * Use parentheses to enforce precedence with `AND`/`OR`.
                        * Handle cumulative fields carefully (e.g., `runs_scored_by_batter_cumulative`).
                        * Always apply `LIMIT {{top_k}}` unless the user **explicitly requests all results**.
                        * Deduplicate results safely when IDs + constraints allow.

                        #### 5. Column Hints

                        * Use `column_hints = {columns_list}` to map natural language to DB columns.
                        * If user asks “highest runs,” map → `runs_scored`.
                        * Always prefer **ID joins + hints** over name-only queries.

                        #### 6. Handling Missing Data

                        * Never invent values.
                        * If a field is `NULL` or missing → explicitly output **“not available”**.

                        #### 7. Integrity & Constraints

                        * Respect unique constraints:

                        * `match_id + inning_team + batter_id`
                        * `match_id + inning_team + wickets_lost_cumulative`
                        * Avoid double-counting in aggregates.

                        #### 8. Error Handling

                        * If query fails:

                        1. Fix syntax and retry.
                        2. If still failing, adjust logic and retry.
                        3. Only return actual query results (never fabricated).

                        #### 9. Final Output

                        * Resolve all IDs to names before returning.
                        * You can return the result as it is no need of summarising or humanizing
                        """

                prompt = ChatPromptTemplate.from_messages([("system", system),("human", "{input}"), MessagesPlaceholder("agent_scratchpad")])

                agent = create_sql_agent(
                        llm=llm,
                        db=db,
                        prompt=prompt,
                        agent_type="openai-tools",
                        handle_parsing_errors=True,
                        handle_sql_errors=True,
                        verbose=True
                        )

                try:
                        result = await agent.ainvoke({"input": question})
                except Exception as e:
                        result = f"Error querying table: {str(e)}"

                state["intermediate_results"] = result

                engine.dispose()
                return state
        
        def resolved_entity_checker(state):
                """    
                Conditional edge function to determine the next step based on whether 
                embeddings were successfully retrieved.
                
                Returns:
                        str: Name of the next node in the graph.
                """
                resolved_flag= state.get("resolved_entities", {}).get("resolved_entities", "False")
                if resolved_flag:
                        return "sql_agent"
                else:
                        return "fuzzy_entity_resolver"

        async def generate_answer(state):
                """
                Generate answer from retrieved_results using llm
                """
                question = state["question"]
                retrieved_results = state["intermediate_results"]

                template = """
                You are an expert response generator for cricket-related data.
                You are given the user's question and the retrieved SQL results from one or more tables in the database.
                Your task is to analyze, aggregate, and present the data in a clear, structured, and human-friendly manner that directly answers the user's question.

                Instructions:

                1. Understand the User Query:
                    * Identify exactly what the user wants to know.
                    * Only include information that directly helps answer the question.
                
                2. Analyze Retrieved Data:
                    * You may receive results from multiple tables.
                    * Extract and combine all relevant information needed for the final answer.
                
                3. Generate a Structured and Human Response:
                    * Present the answer in clear, natural language.
                    * Organize information using bullet points, numbered lists, or short paragraphs for readability.
                    * Maintain a professional, concise, and human-like tone.
                    * If numerical data or match stats are included, format them clearly.
                
                4. Avoid Raw Database Output:
                    * Do not return the results as plain lists or JSON.
                    * Convert them into a well-phrased, coherent answer that reads naturally.
                
                5. If Data is Missing:
                    * If the retrieved results do not fully answer the user query, clearly state that only partial information is available.
                    * Do not hallucinate or fabricate data.

                Input Provided:

                * User Question: `{question}`
                * Retrieved SQL Results: `{retrieved_results}`

                Output Requirement:

                * A human-friendly, well-structured answer that directly addresses the user's question.
                * Must be cohesive, readable, and free of database jargon.

                ---

                Example:

                User Question:
                *"Which team won the ICC Cricket World Cup 2023/24, and who was the top run-scorer?"*

                Retrieved SQL Results:

                [
                        ["year": 2011, "winner": "India"],
                        ["player": "Tillakaratne Dilshan", "runs": 500]
                ]

                Expected Final Response:
                *"India won the ICC Cricket World Cup 2023/24. The tournament's top run-scorer was Tillakaratne Dilshan with 500 runs."*

                """

                prompt = PromptTemplate(input_variables=["question","retrieved_results"],template=template)

                rag_chain = (prompt| llm | StrOutputParser())

                result = await rag_chain.ainvoke({"question":user_query,"retrieved_results":retrieved_results})

                return {"question": question, "generation": result}

        agentic_rag = StateGraph(GraphState)

        agentic_rag.add_node("load_all_tables",load_all_tables)
        agentic_rag.add_node("sql_agent", sql_agent_for_relevant_tables)
        agentic_rag.add_node("entity_retrieval", entity_retrieval)
        agentic_rag.add_node("fuzzy_entity_resolver", fuzzy_entity_resolver)
        agentic_rag.add_node("embedding_entity_resolver", embedding_entity_resolver)
        agentic_rag.add_node("generate_answer", generate_answer)

        agentic_rag.set_entry_point("load_all_tables")

        agentic_rag.add_edge("load_all_tables","entity_retrieval")
        agentic_rag.add_edge("entity_retrieval", "embedding_entity_resolver")
        agentic_rag.add_conditional_edges("embedding_entity_resolver", resolved_entity_checker,
                                         {"sql_agent": "sql_agent", "fuzzy_entity_retrieval": "fuzzy_entity_resolver"})
        agentic_rag.add_edge("fuzzy_entity_resolver", "sql_agent")
        # agentic_rag.add_edge("sql_agent", "generate_answer")
        agentic_rag.add_edge("sql_agent", END)

        agentic_rag = agentic_rag.compile()
        
        print("Starting ODI RAG Agent...")
        time.sleep(0.5)
        response = await agentic_rag.ainvoke({"question":user_query})
        # print("t20i response:",response["generation"])
        return response["intermediate_results"]



